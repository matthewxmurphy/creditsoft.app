<script>
(function () {
    const menu = document.getElementById('mobileMenu');
    const toggle = document.querySelector('[data-mobile-menu-toggle]');
    const group = menu ? menu.querySelector('[data-mobile-menu-group]') : null;
    const submenuToggle = menu ? menu.querySelector('[data-mobile-submenu-toggle]') : null;
    const root = document.documentElement;

    if (!menu || !toggle) {
        return;
    }

    function setMenuOffset() {
        const header = document.querySelector('.site-header');
        const bottom = header ? Math.ceil(header.getBoundingClientRect().bottom) : 150;
        root.style.setProperty('--creditsoft-mobile-menu-top', `${Math.max(bottom, 92)}px`);
    }

    function closeMenu() {
        toggle.classList.remove('active');
        toggle.setAttribute('aria-expanded', 'false');
        toggle.setAttribute('aria-label', 'Open menu');
        menu.classList.remove('active');
        menu.setAttribute('aria-hidden', 'true');
        document.body.classList.remove('creditsoft-menu-open');
    }

    function openMenu() {
        setMenuOffset();
        toggle.classList.add('active');
        toggle.setAttribute('aria-expanded', 'true');
        toggle.setAttribute('aria-label', 'Close menu');
        menu.classList.add('active');
        menu.setAttribute('aria-hidden', 'false');
        document.body.classList.add('creditsoft-menu-open');
    }

    window.toggleMenu = function toggleMenu(forceOpen) {
        const shouldOpen = typeof forceOpen === 'boolean' ? forceOpen : !menu.classList.contains('active');
        if (shouldOpen) {
            openMenu();
        } else {
            closeMenu();
        }
    };

    toggle.addEventListener('click', () => window.toggleMenu());
    menu.addEventListener('click', (event) => {
        if (event.target === menu || event.target.closest('a')) {
            closeMenu();
        }
    });

    if (group && submenuToggle) {
        submenuToggle.addEventListener('click', () => {
            const isOpen = group.classList.toggle('is-open');
            submenuToggle.setAttribute('aria-expanded', String(isOpen));
        });
    }

    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape') {
            closeMenu();
        }
    });
    window.addEventListener('resize', setMenuOffset);
    window.addEventListener('orientationchange', setMenuOffset);
    setMenuOffset();
})();
</script>
