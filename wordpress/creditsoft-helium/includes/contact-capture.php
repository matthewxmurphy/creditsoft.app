/** Read one existing, published, regular non-payment form without modifying it. */
function creditsoft_helium_intake_form(int $formId)
{
    if ($formId < 1 || !shortcode_exists('fluentform') || !class_exists('FluentForm\\App\\Models\\Form')) {
        return null;
    }
    $form = \FluentForm\App\Models\Form::find($formId);
    if (!$form || $form->status !== 'published' || $form->type !== 'form'
        || (int) $form->has_payment !== 0 || trim((string) $form->title) === '') {
        return null;
    }
    $fields = json_decode((string) $form->form_fields, true);
    return is_array($fields) && !empty($fields['fields']) ? $form : null;
}

/** Reusable native form placement; invalid or unavailable bindings emit no dead controls. */
function creditsoft_helium_intake_shortcode($attributes): string
{
    $attributes = shortcode_atts(['form_id' => ''], is_array($attributes) ? $attributes : [], 'creditsoft_intake');
    $value = $attributes['form_id'];
    if (!is_string($value) && !is_int($value)) {
        return '';
    }
    $formId = filter_var($value, FILTER_VALIDATE_INT, ['options' => ['min_range' => 1]]);
    if ($formId === false || !creditsoft_helium_intake_form($formId)) {
        return '';
    }
    return do_shortcode('[fluentform id="' . $formId . '"]');
}
add_shortcode('creditsoft_intake', 'creditsoft_helium_intake_shortcode');

/** Preserve the source of a marked intake submitted through a subdirectory site. */
function creditsoft_helium_intake_source_url(array $submission): array
{
    $posted = $_POST['data'] ?? null;
    if (!wp_doing_ajax() || ($_POST['action'] ?? '') !== 'fluentform_submit' || !is_string($posted)) {
        return $submission;
    }

    $site = trailingslashit(site_url('/'));
    $base = wp_parse_url($site, PHP_URL_PATH);
    if (!is_string($base) || $base === '/' || !str_starts_with($base, '/') || str_starts_with($base, '//')) {
        return $submission;
    }

    parse_str(wp_unslash($posted), $payload);
    $referrer = $payload['_wp_http_referer'] ?? null;
    if (!is_string($referrer) || !str_starts_with($referrer, $base)
        || str_contains($referrer, '#') || sanitize_url($referrer) !== $referrer) {
        return $submission;
    }

    $path = wp_parse_url($referrer, PHP_URL_PATH);
    if (!is_string($path)) {
        return $submission;
    }
    $decodedPath = rawurldecode($path);
    if (str_contains($decodedPath, '\\') || preg_match('~/(?:\.{1,2})(?:/|$)~', $decodedPath)) {
        return $submission;
    }

    // Replace only the source and stored referrer generated by Fluent Forms from this request.
    $nativeReferrer = sanitize_text_field(sanitize_url(urldecode($referrer)));
    $response = $submission['response'] ?? null;
    $fields = is_string($response) ? json_decode($response, true) : null;
    if (!is_array($fields) || ($submission['source_url'] ?? '') !== site_url($nativeReferrer)
        || ($fields['_wp_http_referer'] ?? '') !== $nativeReferrer) {
        return $submission;
    }

    $formId = (int) ($submission['form_id'] ?? 0);
    if ($formId < 1 || !class_exists(\FluentForm\App\Models\FormMeta::class)) {
        return $submission;
    }
    $settings = \FluentForm\App\Models\FormMeta::retrieve('formSettings', $formId, []);
    $classes = $settings['form_extra_css_class'] ?? '';
    if (!is_string($classes) || !in_array('creditsoft-local-capture', preg_split('/\s+/', trim($classes)), true)) {
        return $submission;
    }

    $sourceUrl = $site . substr($referrer, strlen($base));
    if (strlen($sourceUrl) > 255) {
        return $submission;
    }

    $fields['_wp_http_referer'] = $referrer;
    $response = wp_json_encode($fields, JSON_UNESCAPED_UNICODE);
    if ($response !== false) {
        $submission['source_url'] = $sourceUrl;
        $submission['response'] = $response;
    }
    return $submission;
}
add_filter('fluentform/filter_insert_data', 'creditsoft_helium_intake_source_url');

/** Place the operator-selected form after a virtual tool or the tools index. */
add_filter('creditsoft_financial_tools_virtual_after_content', static function (string $after): string {
    $form = creditsoft_helium_intake_shortcode([
        'form_id' => get_option('creditsoft_tools_intake_form_id', ''),
    ]);
    if ($form === '') {
        return $after;
    }

    return $after . '<section class="creditsoft-tools-intake" aria-labelledby="creditsoft-tools-intake-title">'
        . '<h2 id="creditsoft-tools-intake-title">Contact CreditSoft</h2>'
        . '<p>Use this form to contact CreditSoft. Calculator entries stay in your browser.</p>'
        . $form . '</section>';
});

/** Read-only export preparation; choose an existing form and import the resulting Page deliberately. */
function creditsoft_helium_contact_template(int $formId): array
{
    if (!creditsoft_helium_intake_form($formId)) {
        throw new InvalidArgumentException('Select an existing published Fluent Forms contact form.');
    }
    $path = get_stylesheet_directory() . '/content/contact-us.elementor.json';
    if (!is_readable($path)) {
        throw new RuntimeException('CreditSoft Contact source template is unavailable.');
    }
    $template = json_decode((string) file_get_contents($path), true);
    if (!is_array($template) || !isset($template['content']) || !is_array($template['content'])) {
        throw new RuntimeException('CreditSoft Contact source template is unavailable.');
    }
    $marker = '[creditsoft_intake form_id="__CREDITSOFT_FORM_ID__"]';
    $bound = 0;
    $walk = static function (array &$elements) use (&$walk, $marker, $formId, &$bound): void {
        foreach ($elements as &$element) {
            if (!is_array($element)) {
                continue;
            }
            if (($element['widgetType'] ?? null) === 'shortcode' && ($element['settings']['shortcode'] ?? null) === $marker) {
                $element['settings']['shortcode'] = '[creditsoft_intake form_id="' . $formId . '"]';
                $bound++;
            }
            if (isset($element['elements']) && is_array($element['elements'])) {
                $walk($element['elements']);
            }
        }
    };
    $walk($template['content']);
    if ($bound !== 1) {
        throw new RuntimeException('CreditSoft Contact source binding is invalid.');
    }
    return creditsoft_helium_rebase_template_links($template);
}
